// apps/pythinker-web/scripts/generate-file-icons.mjs
//
// Generates src/lib/fileIconsData.ts from the `material-icon-theme` package
// (https://github.com/material-extensions/vscode-material-icon-theme, MIT).
// Run after bumping the devDependency:
//
//   pnpm --filter @pymodel/pythinker-web run gen:file-icons
//
// The output is committed. It contains the filename → icon, extension → icon
// and folder name → icon mappings plus every referenced SVG inlined as a raw
// string, so the app resolves file icons synchronously with no network or
// runtime dependency on the package.

import { generateManifest } from 'material-icon-theme';
import { dirname, join, resolve } from 'node:path';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const require = createRequire(import.meta.url);
const iconsDir = join(dirname(require.resolve('material-icon-theme/package.json')), 'icons');

const manifest = generateManifest();

function loadSvg(name) {
  try {
    return readFileSync(join(iconsDir, `${name}.svg`), 'utf8');
  } catch {
    return undefined;
  }
}

/** Copy map entries whose target SVG exists; drop the rest (icon-pack leftovers). */
function collectMap(source, svgs) {
  const result = {};
  for (const [key, iconName] of Object.entries(source ?? {})) {
    if (typeof iconName !== 'string' || iconName === '') continue;
    if (!(iconName in svgs)) {
      const svg = loadSvg(iconName);
      if (svg === undefined) continue;
      svgs[iconName] = svg;
    }
    result[key.toLowerCase()] = iconName;
  }
  return sortMap(result);
}

/** Light overrides: keep only entries that point somewhere different and exist. */
function collectLightMap(lightSource, baseMap, svgs) {
  const result = {};
  for (const [key, iconName] of Object.entries(lightSource ?? {})) {
    const normalized = key.toLowerCase();
    if (baseMap[normalized] === iconName) continue;
    if (!(iconName in svgs)) {
      const svg = loadSvg(iconName);
      if (svg === undefined) continue;
      svgs[iconName] = svg;
    }
    result[normalized] = iconName;
  }
  return sortMap(result);
}

function sortMap(map) {
  return Object.fromEntries(Object.entries(map).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

const svgs = {};
const fileNames = collectMap(manifest.fileNames, svgs);
const fileExtensions = collectMap(manifest.fileExtensions, svgs);
const folderNames = collectMap(manifest.folderNames, svgs);

// Defaults first so they are always present even if some map entry vanished.
for (const name of [manifest.file, manifest.folder].filter(Boolean)) {
  const svg = loadSvg(name);
  if (svg !== undefined && !(name in svgs)) svgs[name] = svg;
}
if (manifest.file === undefined || !(manifest.file in svgs)) {
  throw new Error('default file icon missing from material-icon-theme');
}
if (manifest.folder === undefined || !(manifest.folder in svgs)) {
  throw new Error('default folder icon missing from material-icon-theme');
}

const lightFileNames = collectLightMap(manifest.light?.fileNames, fileNames, svgs);
const lightFileExtensions = collectLightMap(manifest.light?.fileExtensions, fileExtensions, svgs);
const lightFolderNames = collectLightMap(manifest.light?.folderNames, folderNames, svgs);

const pkgVersion = JSON.parse(
  readFileSync(join(dirname(require.resolve('material-icon-theme/package.json')), 'package.json'), 'utf8'),
).version;

function emitRecord(name, record) {
  const lines = Object.entries(record).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  return `export const ${name}: Record<string, string> = {\n${lines.join('\n')}\n};\n`;
}

const header = `// apps/pythinker-web/src/lib/fileIconsData.ts
//
// GENERATED by scripts/generate-file-icons.mjs from material-icon-theme@${pkgVersion}.
// Do not edit by hand — rerun \`pnpm --filter @pymodel/pythinker-web run gen:file-icons\`.
//
// Source: Material Icon Theme — https://github.com/material-extensions/vscode-material-icon-theme
// Icons © Material Extensions, MIT licensed (see LICENSE attribution in the package).
`;

const out = [
  header,
  `export const DEFAULT_FILE_ICON = ${JSON.stringify(manifest.file)};\n`,
  `export const DEFAULT_FOLDER_ICON = ${JSON.stringify(manifest.folder)};\n`,
  emitRecord('FILE_NAMES', fileNames),
  emitRecord('FILE_EXTENSIONS', fileExtensions),
  emitRecord('FOLDER_NAMES', folderNames),
  emitRecord('LIGHT_FILE_NAMES', lightFileNames),
  emitRecord('LIGHT_FILE_EXTENSIONS', lightFileExtensions),
  emitRecord('LIGHT_FOLDER_NAMES', lightFolderNames),
  emitRecord('SVGS', svgs),
].join('\n');

const target = join(pkgRoot, 'src', 'lib', 'fileIconsData.ts');
writeFileSync(target, out);
console.log(
  `fileIconsData.ts written: ${Object.keys(fileNames).length} fileNames, ` +
    `${Object.keys(fileExtensions).length} fileExtensions, ${Object.keys(folderNames).length} folderNames, ` +
    `${Object.keys(svgs).length} svgs (${(out.length / 1024).toFixed(0)} KB)`,
);
